#!/usr/bin/env python3
"""Install a venv-local `sitecustomize.py` that redirects profile caches.

Why this exists
---------------
On this Windows machine, local security software blocks the checkout's
`.venv/Scripts/python.exe` from writing anywhere under the user profile
(`C:\\Users\\<user>\\`). Tools that cache there by default then fail:

  * matplotlib   -> ``~/.matplotlib``                  : WinError 5
  * warp         -> ``~/AppData/Local/NVIDIA/warp``     : PermissionError
  * NVRTC (warp/ ``%TEMP%`` (CUDA kernel build)        : error 6,
    mujoco-warp)                                         "cannot build
                                                         temporary file name"

Shell env vars (``setx``) only help processes started *after* the change and
are easily lost in IDE/embedded terminals, HF-job subprocesses, etc.
``sitecustomize.py`` is imported by CPython at interpreter startup before any
user code, so it covers every process using this venv.

Usage
-----
    python scripts/fix_windows_profile_writes.py          # install / refresh
    python scripts/fix_windows_profile_writes.py --remove # uninstall

Re-run this after recreating the venv (``rm -rf .venv && uv sync``), which
deletes the generated file. No-op on a machine where the profile is writable.
"""

from __future__ import annotations

import argparse
import os
import site
import sys

TEMPLATE = r'''"""Machine-local fix - generated by scripts/fix_windows_profile_writes.py.

This checkout's python.exe is blocked from writing under the user profile, so
matplotlib / warp / NVRTC caches are redirected into <repo>/.cache/.
Regenerate with `python scripts/fix_windows_profile_writes.py`.
"""

import os

_REPO_ROOT = None
try:
    _here = os.path.dirname(os.path.abspath(__file__))
    _probe = _here
    for _ in range(6):
        if os.path.isfile(os.path.join(_probe, "pyproject.toml")):
            _REPO_ROOT = _probe
            break
        _probe = os.path.dirname(_probe)
except Exception:
    _REPO_ROOT = None


def _project_cache(subdir):
    root = _REPO_ROOT or os.getcwd()
    path = os.path.join(root, ".cache", subdir)
    try:
        os.makedirs(path, exist_ok=True)
    except Exception:
        return None
    return path


def _writable(path):
    if not path:
        return False
    probe = os.path.join(path, ".write_probe")
    try:
        with open(probe, "w"):
            pass
        os.remove(probe)
        return True
    except Exception:
        return False


def _redirect(env_var, subdir):
    current = os.environ.get(env_var)
    if current and _writable(current):
        return
    target = _project_cache(subdir)
    if target:
        os.environ[env_var] = target


if _REPO_ROOT is not None:
    _redirect("MPLCONFIGDIR", "matplotlib")
    _redirect("WARP_CACHE_PATH", "warp")
    _redirect("TEMP", "tmp")
    _redirect("TMP", "tmp")

del os
'''


def _site_packages() -> str:
    """Pick the site-packages dir of the interpreter running this script."""
    candidates = [p for p in site.getsitepackages() if "site-packages" in p]
    if not candidates:
        raise SystemExit("could not locate site-packages for this interpreter")
    # Prefer the one inside the active venv.
    for p in candidates:
        if ".venv" in p.lower():
            return p
    return candidates[0]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--remove",
        action="store_true",
        help="delete the generated sitecustomize.py instead of writing it",
    )
    args = ap.parse_args()

    try:
        sp = _site_packages()
    except SystemExit as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    target = os.path.join(sp, "sitecustomize.py")
    py = sys.executable
    is_venv = ".venv" in py.lower() or os.path.sep + "venv" in py.lower()

    if args.remove:
        if os.path.isfile(target):
            os.remove(target)
            print(f"removed {target}")
        else:
            print(f"nothing to remove ({target} does not exist)")
        return 0

    if not is_venv:
        print(
            f"warning: {py} does not look like the project venv. Run this via\n"
            f"         `uv run python scripts/fix_windows_profile_writes.py`\n"
            f"         so the fix lands in .venv, not your system Python.",
            file=sys.stderr,
        )

    with open(target, "w", encoding="utf-8") as f:
        f.write(TEMPLATE)
    print(f"wrote {target}")
    print("verify with:  uv run python -c \"import matplotlib; print(matplotlib.get_cachedir())\"")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
